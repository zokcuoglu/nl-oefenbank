"""Build data/lezen-teksten.json from the text files in this folder (run: python3 scripts/content/lezen/build_teksten.py).

Checks: unique ids, 3 options per question, a valid question pattern (1-17), and that every 'bewijs'
(the sentence that proves the answer) really appears in the text, so the result page can highlight it.
"""
import importlib.util
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
OUT = ROOT / "data" / "lezen-teksten.json"
MINUTES_PER_TEXT = 18  # exam: 110 minutes for 6 texts
DOMEINEN = {"werk", "educatie", "overig"}
TEKSTSOORTEN = {"persuasief", "descriptief", "instructief", "beschouwend"}

# Practice exams, built like the official public exams 2023-2025 (see the beoordelingsmodel PDFs):
# each 6 texts and 35 questions, two texts per domain, mixed text types, the long search text last.
# Every text belongs to exactly one exam (like in the real booklet) but can also be practised on its own.
EXAMENS = [
    {"id": "examen-1", "titel": "Proefexamen 1", "teksten": ["kinderopvang", "buurtbemiddeling", "omscholing", "ziekmelden", "sportschool", "studiegids"]},
    {"id": "examen-2", "titel": "Proefexamen 2", "teksten": ["thuiswerken", "parkeren", "opendag", "verlof", "examentraining", "huurders"]},
]

# Points -> score (500 = pass) from the official public exam 2025 (beoordelingsmodel Lezen I 2025).
# Each question is 1 point. Other years differ slightly (pass at 23 or 24 points), so on our own
# texts this is only an estimate.
SCORE_2025 = [295, 345, 369, 384, 395, 404, 412, 419, 426, 431, 437, 442, 447, 452, 456, 461, 465, 469, 473,
              477, 482, 486, 490, 495, 500, 505, 510, 516, 522, 529, 537, 547, 559, 574, 598, 649]


def load(path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.TEKSTEN


def main():
    patterns = json.loads((ROOT / "data" / "lezen-bank.json").read_text(encoding="utf-8"))["patterns"]
    teksten, ids, qids = [], set(), set()
    for f in sorted(HERE.glob("t[0-9]*.py")):
        for t in load(f):
            assert t["id"] not in ids, f"duplicate text id {t['id']}"
            ids.add(t["id"])
            assert t.get("domein") in DOMEINEN and t.get("tekstsoort") in TEKSTSOORTEN and t.get("inleiding"), f"{t['id']}: domein/tekstsoort/inleiding"
            plain = t["tekst"].replace("## ", "")
            for q in t["vragen"]:
                where = f"{t['id']}/{q['id']}"
                assert q["id"] not in qids, f"{where}: duplicate question id"
                qids.add(q["id"])
                assert len(q["opties"]) in (3, 4) and len(set(q["opties"])) == len(q["opties"]), f"{where}: needs 3 or 4 different options"
                assert 1 <= q["patroon"] <= len(patterns), f"{where}: pattern"
                assert q["bewijs"] in plain, f"{where}: 'bewijs' not found in the text: {q['bewijs']}"
                q["juist"] = 0  # right answer first in the file; the page shuffles
            t["woorden"] = len(re.findall(r"[\wÀ-ÿ'-]+", plain))
            t["minuten"] = MINUTES_PER_TEXT
            teksten.append(t)
    by_id = {t["id"]: t for t in teksten}
    used = [i for e in EXAMENS for i in e["teksten"]]
    assert sorted(used) == sorted(ids), "every text must be in exactly one exam"
    for e in EXAMENS:
        ts = [by_id[i] for i in e["teksten"]]
        assert len(ts) == 6, f"{e['id']}: needs 6 texts"
        n = sum(len(t["vragen"]) for t in ts)
        assert n == len(SCORE_2025) - 1, f"{e['id']}: {n} questions, score table is for {len(SCORE_2025) - 1}"
        assert sorted(t["domein"] for t in ts) == ["educatie", "educatie", "overig", "overig", "werk", "werk"], f"{e['id']}: domains"
        assert ts[-1].get("zoektekst") and not any(t.get("zoektekst") for t in ts[:-1]), f"{e['id']}: search text must be last"
        for k, t in enumerate(ts):
            t["examen"], t["nr"] = e["id"], k + 1
        e.update(minuten=110, vragen=n)
    teksten = [by_id[i] for i in used]  # exam order
    data = {"_about": "Own practice texts in the style of Staatsexamen NT2 Programma I Lezen. Generated by scripts/content/lezen/build_teksten.py.",
            "patronen": patterns, "teksten": teksten, "examens": EXAMENS,
            "score": SCORE_2025, "geslaagd": 24}
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(teksten)} texts, {len(qids)} questions -> {OUT}")
    for t in teksten:
        print(f"  {t['examen']} {t['nr']}. {t['id']} ({t['domein']}/{t['tekstsoort']}): {t['woorden']} words, {len(t['vragen'])} questions, patterns {sorted(q['patroon'] for q in t['vragen'])}")


if __name__ == "__main__":
    main()
