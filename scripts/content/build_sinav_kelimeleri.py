"""Build data/sinav-kelimeleri.json: which topics and which B1+ words come up most in the official Lezen exams.

Why: the official exams 2023, 2024 and 2025 (Staatsexamen NT2 Lezen I) are mostly about work and education.
This file feeds the 16:9 overview page (lezen/sinav-kelimeleri.html) and the "words of the exam" block in the
Lezen mails. Easy words (A0-A2) are left out: the learner knows them already.

Sources:
  - word counts: data/lezen-bank.json "words" (n = times in the three exams, y = in how many of the 3 years)
  - level, meaning, word page: the single word source (data/woorden.json)
  - text topics: the 18 text titles of the three exam booklets, topic chosen by us (TEKSTEN below)

Run after build_nieuws.py:  python3 scripts/content/build_sinav_kelimeleri.py
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
load = lambda p: json.loads((ROOT / p).read_text(encoding="utf-8"))
LEVELS = ["A0", "A1", "A2", "B1", "B2", "C1", "C2"]
MIN_LEVEL = "B1"
SKIP = {"tekst", "vraag", "lezer"}           # instruction words of the exam booklet itself
ALIAS = {"buren": "buur", "enige": "enig", "zowel": "zowel … als"}   # exam form -> pool entry

# Topics of the 18 exam texts (title from the booklet, topic = our choice)
THEMAS = {"werk": "İş", "opleiding": "Eğitim", "geld": "Para ve sözleşme", "zorg": "Sağlık ve bakım", "dagelijks": "Günlük yaşam"}
TEKSTEN = [
    ("2023", "Vijf fabels over mbo-opleidingen van Ameda", "opleiding"), ("2023", "De rol van de ondernemingsraad", "werk"),
    ("2023", "Maakt geld ons gelukkig?", "geld"), ("2023", "Emma is dolfijnentrainer", "werk"),
    ("2023", "Maak het verschil, word buddy!", "zorg"), ("2023", "Examenreglement", "opleiding"),
    ("2024", "Bakkerij (werken bij Marké)", "werk"), ("2024", "De beursstand", "werk"),
    ("2024", "Verzuim op het werk", "werk"), ("2024", "Met deze opleiding heb je echt een voorsprong", "opleiding"),
    ("2024", "Arbeidsmarkt: jongere op zoek naar zekerheid", "werk"), ("2024", "Abonnement Wonderrijk", "geld"),
    ("2025", "Ruud wordt rij-instructeur", "werk"), ("2025", "Een potje huilen", "zorg"),
    ("2025", "Verkopen is een vak", "werk"), ("2025", "Overuren", "werk"),
    ("2025", "De buurt-whatsapp", "dagelijks"), ("2025", "Algemene informatie Vision College", "opleiding"),
]
# Word groups of the bank (konu) as shown on the page, in this order
GROEPEN = [("is", "İş kelimeleri"), ("egitim", "Eğitim kelimeleri"), ("para", "Para, sözleşme ve kurallar"),
           ("saglik", "Sağlık, bakım ve günlük yaşam"), ("baglac", "Bağlaçlar (metnin mantığı)"), ("fiil", "Sık fiiller"),
           ("genel", "Genel isimler"), ("zarf", "Sıfat ve zarflar"), ("sinav", "Soru dili")]
MERGE = {"gunluk": "saglik"}

key = lambda s: re.sub(r"\(.*?\)|^(de|het|een|zich)\s+", "", s.lower()).strip()

def main():
    pool = {}
    for w in load("data/woorden.json")["woorden"]:
        pool.setdefault(key(w["nl"]), w)
    words, missing = [], []
    for x in load("data/lezen-bank.json")["words"]:
        k = key(x["w"])
        if k in SKIP: continue
        p = pool.get(ALIAS.get(k, k))
        if not p: missing.append(x["w"]); continue
        if LEVELS.index(p["niveau"]) < LEVELS.index(MIN_LEVEL): continue
        words.append({"id": p["id"], "nl": p["nl"], "tr": p["tr"], "niveau": p["niveau"],
                      "groep": MERGE.get(x["konu"], x["konu"]), "n": x["n"], "y": x["y"]})
    if missing:
        raise SystemExit(f"exam words not in the word pool (add them to woorden.csv): {missing}")
    # Ranking: in more exam years first, then more often
    words.sort(key=lambda w: (-w["y"], -w["n"], w["nl"]))
    tel = {t: sum(1 for x in TEKSTEN if x[2] == t) for t in THEMAS}
    (ROOT / "data/sinav-kelimeleri.json").write_text(json.dumps({
        "_about": "Topics and B1+ words of the official Lezen exams 2023-2025. Generated by scripts/content/build_sinav_kelimeleri.py - do not edit.",
        "themas": [{"id": t, "tr": THEMAS[t], "teksten": tel[t]} for t in sorted(THEMAS, key=lambda t: -tel[t])],
        "teksten": [{"jaar": j, "titel": ti, "thema": th} for j, ti, th in TEKSTEN],
        "groepen": [{"id": g, "tr": tr} for g, tr in GROEPEN],
        "woorden": words}, ensure_ascii=False, indent=0) + "\n", encoding="utf-8")
    print(f"{len(words)} words ({MIN_LEVEL}+), {len(TEKSTEN)} texts -> data/sinav-kelimeleri.json")

if __name__ == "__main__":
    main()
