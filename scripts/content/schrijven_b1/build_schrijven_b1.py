"""Build data/schrijven-b1.json (run: python3 scripts/content/schrijven_b1/build_schrijven_b1.py).

Staatsexamen NT2 Schrijven I: on the computer (no spellchecker), 100 minutes, 12 tasks.
Scoring rules below are a short Dutch summary of the CvTE beoordelingsmodel Schrijven I 2025 (openbaar examen),
the point-to-score table is copied from that model (max 47, pass 25 points = 503). The page uses them for the AI prompt.
"""
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent.parent / "data" / "schrijven-b1.json"
GRAM = {"hoofdzin": "een hoofdzin", "bijzin": "een bijzin (werkwoord achteraan)", "inversie": "een hoofdzin met inversie", "te-inf": "een 'te + infinitief'-constructie"}

REGELS = {
    "bron": "CvTE, beoordelingsmodel Schrijven I, openbaar examen 2025",
    "max": 47, "cesuur": 25,
    "tabel": [300, 341, 363, 378, 389, 399, 407, 415, 422, 428, 434, 439, 445, 450, 455, 459, 464, 468, 473, 477, 482, 486, 490, 495, 498, 503,
              508, 512, 517, 521, 526, 530, 535, 540, 545, 550, 555, 561, 567, 573, 579, 586, 593, 602, 612, 625, 643, 681],
    "zin": "Opdracht 1-8 (zinstaak): adequaatheid/begrijpelijkheid 0-1 (de tekst is een adequate reactie op de opdracht) en grammaticale correctheid 0-1. "
           "Bij 0 voor adequaatheid wordt niet verder beoordeeld. Als er een constructie gevraagd wordt (hoofdzin, bijzin, inversie, te + infinitief), "
           "moet die er zijn voor 1 punt grammatica; de woordvolgorde moet altijd correct zijn.",
    "formulier": "Opdracht 9 (deelschrijftaak, formulier): adequaatheid 0-3 (2 = acceptabel: formulier volledig ingevuld; 3 = uitstekend; "
                 "bij maar een deel van de opdracht maximaal 2), grammatica 0-2 (veel / enkele / nauwelijks of geen fouten), spelling 0-1, woordgebruik 0-1. Max 7.",
    "tekst": "Opdracht 10-12 (deelschrijftaak/korte schrijftaak): adequaatheid 0-3 (2 = acceptabel als alle gevraagde elementen erin staan; "
             "3 of 1 op basis van de totale kwaliteit; bij maar een deel van de opdracht maximaal 2; bijlagen zoals plaatjes of tabellen komen niet mee, "
             "dus de tekst moet zonder bijlage te begrijpen zijn), grammatica 0-2, spelling 0-1, samenhang 0-1 (verbindingswoorden), woordgebruik 0-1. Max 8.",
    "algemeen": [
        "Schalen worden onafhankelijk van elkaar gebruikt; een onzekere score op de ene schaal compenseer je niet met een andere.",
        "Letterlijk overgeschreven zinnen uit de opdracht krijgen geen punten.",
        "Overbodige toevoegingen met fouten tellen mee in de beoordeling; zonder fouten hebben ze geen invloed.",
        "Adequaatheid wordt tolerant beoordeeld; de waarheid van de inhoud telt niet.",
        "Fouten tegen het woordgeslacht (de/het) en wat daaruit volgt mogen; een vergeten lidwoord is wel een fout.",
    ],
}


def load(name):
    spec = importlib.util.spec_from_file_location(name, HERE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    return mod


def main():
    mod, kal = load("taken"), load("kaliplar")
    ids = set()
    for e in mod.EXAMENS:
        ts = e["taken"]
        assert [t["soort"] for t in ts] == ["zin"] * 8 + ["formulier"] + ["tekst"] * 3, e["id"]
        for k, t in enumerate(ts, 1):
            assert t["id"] not in ids, t["id"]; ids.add(t["id"])
            assert t["voorbeeld"] and t["tr"], t["id"]
            if t["soort"] == "zin":
                assert t["gram"] in (None, *GRAM), t["id"]
                t["gram_tekst"] = GRAM.get(t["gram"])
            t["nr"] = k
            t["kalip"] = kal.kalip_van(t)  # task type -> tactics + hint box (kaliplar.py)
            assert t["kalip"] in kal.KALIPLAR, t["id"]
            t["max"] = 2 if t["soort"] == "zin" else 7 if t["soort"] == "formulier" else 8
        assert sum(t["max"] for t in ts) == REGELS["max"], e["id"]
        e["minuten"] = 100
    assert len(REGELS["tabel"]) == REGELS["max"] + 1
    OUT.write_text(json.dumps({"_about": "Own Schrijven I (B1) practice tasks + scoring summary. Generated by scripts/content/schrijven_b1/build_schrijven_b1.py.",
                               "examens": mod.EXAMENS, "regels": REGELS,
                               "algemeen": kal.ALGEMEEN, "kaliplar": kal.KALIPLAR}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(ids)} tasks in {len(mod.EXAMENS)} exams -> {OUT}")


if __name__ == "__main__":
    main()
