"""Build data/luisteren-a2.json from fragmenten.py (run: python3 scripts/content/luisteren_a2/build_luisteren_a2.py).

A2 inburgeringsexamen Luisteren: on the computer, 45 minutes, videos and spoken texts with multiple-choice questions.
The page reads our fragments aloud with the browser's Dutch voice (no video). Checks: unique ids, 3 different options,
known speakers, and that 'bewijs' is one of the spoken sentences.
"""
import importlib.util
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent.parent / "data" / "luisteren-a2.json"
SPEAKERS = {"v", "v2", "m", "o"}  # woman, second woman, man, announcement


def main():
    spec = importlib.util.spec_from_file_location("fragmenten", HERE / "fragmenten.py")
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    ids, exams = set(), []
    for e in mod.EXAMENS:
        frs = []
        for f in e["fragmenten"]:
            assert f["id"] not in ids, f"duplicate id {f['id']}"; ids.add(f["id"])
            lines = []
            for raw in f["tekst"].split("\n"):
                who, text = raw.split(":", 1)
                assert who.strip() in SPEAKERS, f"{f['id']}: speaker {who}"
                lines.append([who.strip(), text.strip()])
            assert any(f["bewijs"] in t for _, t in lines), f"{f['id']}: bewijs not spoken: {f['bewijs']}"
            assert len(f["opties"]) == 3 and len(set(f["opties"])) == 3, f"{f['id']}: 3 different options"
            frs.append({**f, "regels": lines, "juist": 0, "woorden": sum(len(re.findall(r"[\wÀ-ÿ'-]+", t)) for _, t in lines)})
            del frs[-1]["tekst"]
        exams.append({"id": e["id"], "titel": e["titel"], "minuten": 45, "fragmenten": frs})
    OUT.write_text(json.dumps({"_about": "Own A2 Luisteren practice fragments. Generated by scripts/content/luisteren_a2/build_luisteren_a2.py.",
                               "examens": exams}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(ids)} fragments in {len(exams)} exams -> {OUT}")


if __name__ == "__main__":
    main()
