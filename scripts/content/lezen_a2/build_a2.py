"""Build data/lezen-a2.json from the text files in this folder (run: python3 scripts/content/lezen_a2/build_a2.py).

A2 inburgeringsexamen Lezen: on the computer, 65 minutes, everyday texts with multiple-choice questions.
Our practice exams: 8 short texts and 25 questions each. DUO publishes no fixed number of questions or pass mark;
"about 18 of 25" is the guideline used by practice sites (not official), so the page only shows it as an estimate.

Same JSON shape as data/lezen-teksten.json (B1), so lezen/teksten.html can show both (?set=a2).
Checks: unique ids, 3 options, valid question pattern, every 'bewijs' really appears in the text, 25 questions per exam.
"""
import importlib.util
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
OUT = ROOT / "data" / "lezen-a2.json"
EXAM_MINUTES = 65
MINUTES_PER_TEXT = 8  # 65 minutes / 8 texts, rounded
QUESTIONS_PER_EXAM = 25
PASS_GUIDE = 18  # not official, see above

EXAMENS = [
    {"id": "a2-examen-1", "titel": "A2 proefexamen 1", "teksten": ["a2-schoolreis", "a2-bibliotheek-tijden", "a2-huisarts", "a2-fiets-te-koop", "a2-afval", "a2-sportclub", "a2-zwembad", "a2-pakketje"]},
    {"id": "a2-examen-2", "titel": "A2 proefexamen 2", "teksten": ["a2-werkrooster", "a2-buslijn", "a2-tandarts", "a2-buurtfeest", "a2-onderhoud", "a2-bezorgen", "a2-bieb-regels", "a2-ouderavond"]},
]


def load(path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.TEKSTEN


def main():
    patterns = json.loads((ROOT / "data" / "lezen-bank.json").read_text(encoding="utf-8"))["patterns"]
    teksten, ids, qids = [], set(), set()
    for f in sorted(HERE.glob("a[0-9]*.py")):
        for t in load(f):
            assert t["id"] not in ids, f"duplicate text id {t['id']}"
            ids.add(t["id"])
            assert t.get("soort") and t.get("inleiding"), f"{t['id']}: soort/inleiding"
            plain = t["tekst"].replace("## ", "")
            for q in t["vragen"]:
                where = f"{t['id']}/{q['id']}"
                assert q["id"] not in qids, f"{where}: duplicate question id"
                qids.add(q["id"])
                assert len(q["opties"]) == 3 and len(set(q["opties"])) == 3, f"{where}: needs 3 different options"
                assert 1 <= q["patroon"] <= len(patterns), f"{where}: pattern"
                assert q["bewijs"] in plain, f"{where}: 'bewijs' not found in the text: {q['bewijs']}"
                q["juist"] = 0  # right answer first in the file; the page shuffles
            t["woorden"] = len(re.findall(r"[\wÀ-ÿ'-]+", plain))
            t["minuten"] = MINUTES_PER_TEXT
            teksten.append(t)
    by_id = {t["id"]: t for t in teksten}
    used = [i for e in EXAMENS for i in e["teksten"]]
    assert sorted(used) == sorted(ids), "every text must be in exactly one exam"
    for e in EXAMENS:
        ts = [by_id[i] for i in e["teksten"]]
        n = sum(len(t["vragen"]) for t in ts)
        assert n == QUESTIONS_PER_EXAM, f"{e['id']}: {n} questions, expected {QUESTIONS_PER_EXAM}"
        for k, t in enumerate(ts):
            t["examen"], t["nr"] = e["id"], k + 1
        e.update(minuten=EXAM_MINUTES, vragen=n)
    data = {"_about": "Own practice texts in the style of the A2 inburgeringsexamen Lezen. Generated by scripts/content/lezen_a2/build_a2.py.",
            "niveau": "A2", "patronen": patterns, "teksten": [by_id[i] for i in used], "examens": EXAMENS,
            "score": None, "geslaagd": PASS_GUIDE}
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(teksten)} texts, {len(qids)} questions -> {OUT}")
    for t in data["teksten"]:
        print(f"  {t['examen']} {t['nr']}. {t['id']} ({t['soort']}): {t['woorden']} words, {len(t['vragen'])} questions")


if __name__ == "__main__":
    main()
