"""Build data/luisteren-b1.json (run: python3 scripts/content/luisteren_b1/build_luisteren_b1.py).

Staatsexamen NT2 Programma I Luisteren (per the official site, as quoted by practice sites): on the computer, 90 minutes,
5 or more listening texts and 1-3 films, about 40 multiple-choice questions, each fragment plays once (no pause, no replay),
25 seconds reading time per question before the fragment starts. Pass = score 500.
Our practice exams: 10 texts with 4 questions = 40 questions, 90 minutes; the page reads the texts aloud with the browser's
Dutch voice(s). A text may have 'video_url' (+ 'video_start'/'video_end'): then the page plays that video instead.
Same JSON shape as data/luisteren-a2.json, so luisteren-a2/index.html shows both (?set=b1).
"""
import importlib.util
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent.parent / "data" / "luisteren-b1.json"
SPEAKERS = {"v", "v2", "m", "m2", "o"}


def load(name):
    spec = importlib.util.spec_from_file_location(name, HERE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    return mod.TEKSTEN


def main():
    ids, qids, exams = set(), set(), []
    for k, name in enumerate(["examen1", "examen2"], 1):
        frs = []
        for t in load(name):
            assert t["id"] not in ids, t["id"]; ids.add(t["id"])
            lines = []
            for raw in t["tekst"].strip().split("\n"):
                who, text = raw.split(":", 1)
                assert who.strip() in SPEAKERS, f"{t['id']}: speaker {who}"
                lines.append([who.strip(), text.strip()])
            for q in t["vragen"]:
                assert q["id"] not in qids, q["id"]; qids.add(q["id"])
                assert len(q["opties"]) == 3 and len(set(q["opties"])) == 3, q["id"]
                assert any(q["bewijs"] in s for _, s in lines), f"{q['id']}: bewijs not spoken: {q['bewijs']}"
                q["juist"] = 0
            frs.append({"id": t["id"], "intro": t["intro"], "regels": lines, "vragen": t["vragen"],
                        "woorden": sum(len(re.findall(r"[\wÀ-ÿ'-]+", s)) for _, s in lines),
                        **{key: t[key] for key in ("video_url", "video_start", "video_end") if key in t}})
        n = sum(len(f["vragen"]) for f in frs)
        assert n == 40, f"{name}: {n} questions"
        exams.append({"id": f"lb-examen-{k}", "titel": f"B1 Luisteren proefexamen {k}", "minuten": 90, "fragmenten": frs})
    OUT.write_text(json.dumps({"_about": "Own B1 Luisteren practice texts. Generated by scripts/content/luisteren_b1/build_luisteren_b1.py.",
                               "niveau": "B1", "examens": exams}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(ids)} texts, {len(qids)} questions -> {OUT}")


if __name__ == "__main__":
    main()
