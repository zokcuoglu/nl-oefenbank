"""Build data/nieuws.json from the item files in this folder (run: python3 scripts/content/build_nieuws.py).

The item files are the place to edit content; this script only assembles and checks them:
unique ids, valid answers, a ___ in every gap question, all five levels present.
"""
import importlib.util
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "data" / "nieuws.json"
LEVELS = ["a0", "a1", "a2", "b1", "b2", "c1"]
# Every item quiz has 18 questions with this spread, so item scores are comparable
ITEM_QUIZ = {"begrip": 5, "woorden": 4, "uitdrukkingen": 5, "grammatica": 4}
# Every mixed test has 20 questions with the same spread (6/5/5/4), so test scores are comparable.
# Test 1 (news 1-3): all 20 from items 1-3 and its own mixed questions.
# Later tests (1-4, 1-5, ...): 12 from the newest item, 8 review questions from all earlier items
# (the page picks questions the user got wrong last time first, then the test's own mixed questions).
TOETS_FIRST = {"nieuw": {"begrip": 6, "woorden": 5, "uitdrukkingen": 5, "grammatica": 4}, "herhaling": {}}
TOETS_LATER = {"nieuw": {"begrip": 4, "woorden": 3, "uitdrukkingen": 3, "grammatica": 2},
               "herhaling": {"begrip": 2, "woorden": 2, "uitdrukkingen": 2, "grammatica": 2}}


def load(path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check_questions(qs, where, seen):
    for q in qs:
        assert q["id"] not in seen, f"{where}: duplicate question id {q['id']}"
        seen.add(q["id"])
        assert q["type"] in ("mc", "tf", "gap"), f"{where}/{q['id']}: type"
        assert q["cat"] in ("begrip", "woorden", "uitdrukkingen", "grammatica"), f"{where}/{q['id']}: cat"
        assert q["niveau"] in ("A1", "A2", "B1", "B2", "C1"), f"{where}/{q['id']}: niveau"
        assert 0 <= q["juist"] < len(q["opties"]), f"{where}/{q['id']}: juist"
        assert len(set(q["opties"])) == len(q["opties"]), f"{where}/{q['id']}: duplicate option"
        if q["type"] == "gap":
            assert "___" in q["vraag"], f"{where}/{q['id']}: gap without ___"
        if q["type"] == "tf":
            assert q["opties"] == ["Waar", "Niet waar"], f"{where}/{q['id']}: tf options"


def main():
    items, seen_q = [], set()
    for f in sorted(HERE.glob("n[0-9][0-9]_*.py")):
        it = dict(load(f).ITEM)
        for l in LEVELS:
            assert it.get(l), f"{f.name}: missing {l}"
        it["gloss"] = {l: it.pop(f"gloss_{l}") for l in LEVELS if f"gloss_{l}" in it}
        for line in it["woordenschat"].splitlines():
            assert len(line.split("|")) == 6, f"{f.name}: woordenschat line needs 6 columns: {line}"
        check_questions(it["toets"], f.name, seen_q)
        cats = {c: sum(q["cat"] == c for q in it["toets"]) for c in ITEM_QUIZ}
        assert cats == ITEM_QUIZ, f"{f.name}: quiz spread {cats}, expected {ITEM_QUIZ}"
        items.append(it)
    nrs = [i["nr"] for i in items]
    assert nrs == sorted(nrs) and len(set(nrs)) == len(nrs), "item numbers must be unique and in order"

    toetsen = load(HERE / "toetsen.py").TOETSEN
    ids = {i["id"] for i in items}
    nrs_all = {i["nr"] for i in items}
    for k, t in enumerate(toetsen):
        check_questions(t["extra"], t["id"], seen_q)
        if t["tot"] not in nrs_all:
            continue  # test for an item that is not written yet: kept in the file, left out of the site
        first = k == 0
        # items = the part most questions come from; vorige = earlier items for the review part
        t["items"] = [i["id"] for i in items if (i["nr"] <= t["tot"] if first else i["nr"] == t["tot"])]
        t["vorige"] = [] if first else [i["id"] for i in items if i["nr"] < t["tot"]]
        t["opbouw"] = TOETS_FIRST if first else TOETS_LATER
        t["extra_in"] = "nieuw" if first else "herhaling"
        for cat, n in t["opbouw"]["nieuw"].items():
            have = (sum(q["cat"] == cat for q in t["extra"]) if first else 0) + sum(q["cat"] == cat for i in items if i["id"] in t["items"] for q in i["toets"])
            assert have >= n, f"{t['id']}: only {have} {cat} questions for {n}"
    toetsen = [t for t in toetsen if "items" in t]

    data = {
        "_about": "Lezen en kijken in niveaus. Generated by scripts/content/build_nieuws.py - edit the item files there, not this file.",
        "versie": 1,
        "items": items,
        "toetsen": toetsen,
    }
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    words = {i["id"]: {l: len(re.sub(r"<[^>]+>", "", i[l]).split()) for l in LEVELS} for i in items}
    print(f"{len(items)} items, {len(toetsen)} toets(en), {len(seen_q)} questions -> {OUT}")
    for k, v in words.items():
        print(f"  {k}: words per level {v}, idioms {len(next(i for i in items if i['id'] == k)['uitdrukkingen'])}")


if __name__ == "__main__":
    main()
