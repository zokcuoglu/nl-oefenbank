"""Build data/woordenboek.json: a small Dutch-Dutch dictionary for the Lezen pages.

Why: in the real Staatsexamen Lezen exam you may use a Dutch-Dutch dictionary (Van Dale NT2 pocket), but you do
not get Turkish translations. So on the reading page the dictionary shows Dutch only: article, word type,
a Dutch definition and an example. Everything comes from the single word source (woorden.csv /
uitdrukkingen.csv via data/woorden.json), so a definition is written once and used everywhere.

Output:
  e  : lookup key -> list of entries {nl, lw, soort, def, vb}
       key = the word without article, lower case ("de huur" -> "huur"); expressions are keyed on every
       content word, so "van tevoren" is found by "tevoren"
  f  : extra word form -> key, for irregular verbs (liep -> lopen, gekregen -> krijgen) from
       oyunlar/werkwoorden.json. Regular endings (-en, -t, -te, -de, ge-...-d) are stripped in the page itself.

Run after build_nieuws.py (needs data/woorden.json):  python3 scripts/content/build_woordenboek.py
"""
import json, re
from pathlib import Path
from woordbron import entry_words, PHRASE_TUR

ROOT = Path(__file__).resolve().parents[2]
load = lambda p: json.loads((ROOT / p).read_text(encoding="utf-8"))

# Dutch names of the word types, as a Dutch dictionary would show them
SOORT = {"zn": "zelfstandig naamwoord", "ww": "werkwoord", "sch_ww": "scheidbaar werkwoord", "bn": "bijvoeglijk naamwoord",
         "bw": "bijwoord", "klein": "klein woord", "telw": "telwoord", "tw": "tussenwerpsel", "afk": "afkorting",
         "uitdr": "uitdrukking", "vaste_comb": "vaste combinatie", "zin": "zin", "structuur": "zinsstructuur"}

def key_of(nl):
    """Lookup key: lower case, without article and without '(…)' notes."""
    k = re.sub(r"\(.*?\)", "", nl.lower())
    return re.sub(r"^(de|het|een)\s+", "", k).strip()

def main():
    pool = load("data/woorden.json")["woorden"]
    e = {}
    for w in pool:
        lw = (re.match(r"^(de|het)\s", w["nl"].lower()) or [None, ""])[1]
        item = {"nl": w["nl"], "lw": lw, "soort": SOORT.get(w["tur"], ""),
                "def": w.get("definitie", ""), "vb": w.get("voorbeeld", "")}
        keys = {key_of(w["nl"])}
        if w["tur"] in PHRASE_TUR:          # expressions: also findable by each content word
            keys |= set(entry_words(w["nl"]))
        for k in keys:
            if k and item not in e.setdefault(k, []):
                e[k].append(item)
    # Irregular verb forms -> infinitive (only when the infinitive is in the dictionary)
    f = {}
    for v in load("oyunlar/werkwoorden.json")["werkwoorden"]:
        if v["inf"] not in e: continue
        for form in v.get("imp", []) + [v.get("impMv", ""), v.get("vd", "")]:
            form = form.lower().strip()
            if form and form != v["inf"]: f[form] = v["inf"]
    (ROOT / "data/woordenboek.json").write_text(json.dumps({
        "_about": "Dutch-Dutch dictionary for Lezen. Generated by scripts/content/build_woordenboek.py - do not edit.",
        "e": e, "f": f}, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    n_def = sum(1 for lst in e.values() for i in lst if i["def"])
    print(f"{len(e)} keys, {n_def} entries with a definition, {len(f)} verb forms -> data/woordenboek.json")

if __name__ == "__main__":
    main()
