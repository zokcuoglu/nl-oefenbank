"""Build data/tekst-woorden.json: per Lezen text (B1 and A2), the words of the word pool that occur in it.

Why: Lezen texts are exam-style, so words are not clickable while you answer. After "Bitir" the review lists
the words of that text that are in the word pool, each a link to its word page; that ties the reading texts to
the same words as the news, the word tests and the mails.

Run after build_nieuws.py (needs data/woorden.json):  python3 scripts/content/build_tekst_woorden.py
(scripts/build_all.py runs it in the right order.)
"""
import json, re
from pathlib import Path
from woordbron import found_in, entry_words

ROOT = Path(__file__).resolve().parents[2]
load = lambda p: json.loads((ROOT / p).read_text(encoding="utf-8"))
RANK = {l: i for i, l in enumerate(["A0", "A1", "A2", "B1", "B2", "C1", "C2"])}
MIN = {"lezen-teksten.json": "A2", "lezen-a2.json": "A1"}   # very easy words say nothing in a review list
MAX_WORDS = 30

def text_of(t):
    """All Dutch text of a Lezen text (title, paragraphs, questions), without HTML."""
    parts = []
    def walk(x):
        if isinstance(x, str): parts.append(x)
        elif isinstance(x, list):
            for y in x: walk(y)
        elif isinstance(x, dict):
            for k, y in x.items():
                if k not in ("uitleg", "id", "patroon", "bewijs"): walk(y)   # explanations are Turkish
    walk(t)
    return re.sub(r"<[^>]+>", " ", " ".join(parts))

def main():
    pool = [w for w in load("data/woorden.json")["woorden"] if entry_words(w["nl"])]
    out = {}
    for f, low in MIN.items():
        for t in load(f"data/{f}")["teksten"]:
            text = text_of(t)
            low_text = text.lower()
            hits = [w for w in pool if RANK[w["niveau"]] >= RANK[low]
                    and entry_words(w["nl"])[0] in low_text and found_in(w["nl"], text)]
            hits.sort(key=lambda w: (-RANK[w["niveau"]], w["nl"]))
            # nl/tr/niveau are copied here (generated file) so the page does not have to load the whole pool
            out[t["id"]] = [{"id": w["id"], "nl": w["nl"], "tr": w["tr"], "niveau": w["niveau"]} for w in hits[:MAX_WORDS]]
    (ROOT / "data/tekst-woorden.json").write_text(json.dumps({
        "_about": "Pool words per Lezen text, shown after finishing. Generated by scripts/content/build_tekst_woorden.py - do not edit.",
        "teksten": out}, ensure_ascii=False, indent=0) + "\n", encoding="utf-8")
    print(f"{len(out)} texts, {sum(map(len, out.values()))} word links -> data/tekst-woorden.json")

if __name__ == "__main__":
    main()
